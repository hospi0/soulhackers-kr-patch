def norm(t):
    t = re.sub(r'\{[^}]*\}', '', t)
    return t.translate(str.maketrans('０１２３４５６７８９ＡＢＣＤＥＦＧＨＩＪＫＬＭＮＯＰＱＲＳＴＵＶＷＸＹＺ（）', '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ()'))


def main():
    sys.stdout.reconfigure(encoding='utf-8')
    rows = [l.split('\t') for l in open(os.path.join(ROOT, 'data', 'sh_ja.tsv'), encoding='utf-8').read().splitlines()[1:]]
    body = [(r[1], r[4], norm(r[5])) for r in rows]
    miss = 0; susp = 0
    for shot, ws in SHOTS.items():
        for w in ws:
            wn = norm(w).replace('／', '/')
            hit = [b for b in body if wn in b[2].replace('／', '/')]
            if not hit:                                    # 오독 대비: 앞뒤 절반씩
                h = len(wn) // 2
                hit = [b for b in body if len(wn) >= 4 and (wn[:h] in b[2] or wn[h:] in b[2])]
                tag = '부분' if hit else '없음'
            else: tag = '있음'
            if tag == '없음': miss += 1
            if hit and all(b[1] == '의심' for b in hit): tag += '(의심 줄만)'; susp += 1
            if tag != '있음': print('%-10s %-24s %s %s' % (shot, w, tag, ' '.join(sorted({b[0] for b in hit}))[:60]))
    print('문구 %d개 · 없음 %d · 의심 줄에만 %d' % (sum(map(len, SHOTS.values())), miss, susp))


if __name__ == '__main__':
    main()
